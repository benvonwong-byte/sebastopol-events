#!/usr/bin/env node
// Writes docs/needs-a-feed.md: every group we cannot read yet, with the
// links to where it posts events today. This is the buildathon task list;
// the Groups view links to it.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const orgs = JSON.parse(readFileSync(join(ROOT, "data/orgs.json"), "utf8"));
const domains = JSON.parse(readFileSync(join(ROOT, "data/domains.json"), "utf8"));

const missing = orgs.filter((o) => !(o.feeds ?? []).some((f) => !f.disabled));
const lines = [
  "# Groups that need a feed",
  "",
  `${missing.length} of ${orgs.length} groups in the directory post events somewhere this calendar cannot read: a web page, Instagram, a newsletter or a flyer. Each one below is a buildathon task.`,
  "",
  "**The job:** find out where the group keeps its events, then either find a feed we can read (see the table in the README) or help the group set up a free public Google Calendar and add its `.ics` link to `data/orgs.json`. Ask the group first; never publish a private calendar.",
  "",
  "Generated by `npm run tasks` from `data/orgs.json`.",
  "",
];
for (const d of domains) {
  const list = missing.filter((o) => o.domains[0] === d.id).sort((a, b) => a.name.localeCompare(b.name));
  if (!list.length) continue;
  lines.push(`## ${d.label} (${list.length})`, "");
  for (const o of list) {
    const links = [
      `[site](${o.url})`,
      o.eventsPage && o.eventsPage !== o.url ? `[events page](${o.eventsPage})` : null,
      o.instagram ? `[Instagram](${o.instagram})` : null,
    ].filter(Boolean);
    lines.push(`- [ ] **${o.name}** (${o.town ?? (o.area === "nearby" ? "nearby" : "Sebastopol")}): ${links.join(" · ")}`);
  }
  lines.push("");
}
writeFileSync(join(ROOT, "docs/needs-a-feed.md"), lines.join("\n"));
console.log(`needs-feed: ${missing.length} groups listed in docs/needs-a-feed.md`);
